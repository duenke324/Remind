export type Lang = 'pt' | 'en'
export type TKey = Key
export type Translate = (key: Key, vars?: Record<string, string>) => string

const dictionaries: Record<Lang, Record<Key, string>> = { pt, en }

export function translate(lang: Lang, key: Key, vars?: Record<string, string>): string {
  let text = dictionaries[lang][key] ?? pt[key] ?? key
  for (const [name, value] of Object.entries(vars ?? {})) text = text.replaceAll(`{${name}}`, value)
  return text
}

/** Traduz um código de erro do servidor; códigos desconhecidos dão a mensagem genérica. */
export function errorMessage(t: Translate, code: string): string {
  const key = `error.${code}` as Key
  return key in pt ? t(key) : t('error.default')
}

const I18nContext = createContext<{ lang: Lang; t: Translate }>({ lang: 'pt', t: (k, v) => translate('pt', k, v) })

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const value = useMemo(() => ({ lang, t: ((k, v) => translate(lang, k, v)) as Translate }), [lang])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export const useI18n = () => useContext(I18nContext)
